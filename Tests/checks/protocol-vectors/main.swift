/// A P-256 key from a fixed scalar (SHA-256 of a label), so every vector below is reproducible.
struct VectorKey {
    let label: String
    let priv: P256.Signing.PrivateKey
    let secKey: SecKey
    var point: Data { priv.publicKey.x963Representation }
    var fingerprint: Data { SPKI.fingerprint(point: point) }
    init(_ label: String) {
        self.label = label
        priv = try! P256.Signing.PrivateKey(rawRepresentation: Data(SHA256.hash(data: Data(label.utf8))))
        guard let k = RemoteKey.importPrivate(priv.x963Representation) else { fail("import \(label)") }
        secKey = k
    }
    var record: [String: Any] {
        ["scalarFrom": "SHA-256 of the UTF-8 label \"\(label)\"",
         "privateScalar": hex(priv.rawRepresentation),
         "privateX963": hex(priv.x963Representation),
         "publicPoint": hex(point),
         "spkiDER": hex(SPKI.der(point: point)),
         "fingerprint": hex(fingerprint),
         "fingerprintBase64URL": Base64URL.encode(fingerprint),
         "macID": MacID.make(fingerprint: fingerprint),
         "shortName": RemoteIdentity.shortName(fingerprint)]
    }
}
