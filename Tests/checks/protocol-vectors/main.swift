func hex(_ d: Data) -> String { d.map { String(format: "%02x", $0) }.joined() }
func unhex(_ s: String) -> Data {
    var d = Data(); var i = s.startIndex
    while i < s.endIndex { let j = s.index(i, offsetBy: 2); d.append(UInt8(s[i..<j], radix: 16)!); i = j }
    return d
}
func fail(_ s: String) -> Never { FileHandle.standardError.write(Data("protocol-vectors: \(s)\n".utf8)); exit(1) }

/// Swift's JSON for a value, keys sorted. Swift's own order follows the process's hash seed, so a
/// reader must never depend on key order; sorted here only so the file is stable.
let sortedEncoder: JSONEncoder = { let e = JSONEncoder(); e.outputFormatting = [.sortedKeys]; return e }()
func json<T: Encodable>(_ v: T) -> String { String(decoding: try! sortedEncoder.encode(v), as: UTF8.self) }

