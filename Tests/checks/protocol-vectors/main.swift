// Test vectors for a client written outside this repository (docs/protocol/SPEC.md): every byte
// and every JSON shape a client must produce or accept, computed by StreamProtocol's own code, so
// the vectors are what the Mac and the iOS app do, not what a document says they do.
//
//   protocol-vectors OUT.json                 a fresh file (new certificate and kind 18 signature)
//   protocol-vectors OUT.json --reuse IN.json  the same, keeping IN's certificate and signature once
//                                              they verify again: the check's mode, so the output is
//                                              byte for byte the committed file while nothing changed
//
// Compiled with Sources/StreamProtocol/*.swift as one module (run.sh), so internal names are
// reachable. Everything is deterministic but the two randomized values (ECDSA signs with a fresh
// nonce; the certificate has a random serial and name), which --reuse carries over after checking.
