/// What Swift's decoder takes and refuses: the strictness a client's encoder must meet, and the
/// leniency it may rely on when decoding the Mac's payloads.
func probe<T: Codable>(_ t: T.Type, _ name: String, _ text: String) -> [String: Any] {
    var r: [String: Any] = ["name": name, "type": "\(T.self)", "json": text]
    if let v = Wire.decode(T.self, from: Data(text.utf8)) { r["accepted"] = true; r["decodedAs"] = json(v) } else { r["accepted"] = false }
    return r
}
